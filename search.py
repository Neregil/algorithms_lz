from random import randint as ri #Импортирую библиотеку рандома

lp=0 #Счётчик сравнений линейного поиска
bp=0 #И бинарного поиска
st=[] #Создаю коллекцию
for i in range(0,100): #Задаю её размер
    st.append(ri(0,1000000)) #Заполняю её случайными числами и задаю их параметры
ss=sorted(st) #Сортирую быстрой сортировкой
print(ss)#Вывожу свою отсортированную коллекцию
el=int(input("Введите заданный элемент: ")) 
print()
for i in range(len(ss)): #Иду по всей коллекции
    lp+=1 #Счётчкий перед сравнением
    if ss[i]==el: #Проверка на то: подходит ли мне этот элемент
        break #Если да, то прекращаю поиск

ft=0 #От куда мы берём середину
lt=len(ss)-1 #До куда мы берём середину
j=-1 #Нашли ли мы элемент?
while (ft<=lt) and (j==-1): #Проверяю, либо мы прошли всю коллекцию, либо нашли элемент
    m=(ft+lt)//2 #Нахожу середину
    bp+=1 #Счётчкий перед сравнением
    if ss[m]==el: #Проверка на то: подходит ли мне этот элемент
        j=m # j!=-1 - выхожу из цикла
    else:
        bp+=1 #Счётчкий перед сравнением
        if el<ss[m]: #Меньше ли этот элемент искомого
            lt=m-1 #Если да, то уменьшаю верхнюю границу
        else:
            ft=m+1 #Если нет, то увеличиваю нижнюю
if(ss[i]==el): #Был ли найден элемент?
    print(f"Его индекс: {i}")
    print(f"Количество сравнений, сделанных во время линейного поиска: {lp}, бинарного: {bp}")
else:print("Элемент не найден ни в одном из методов")